import { chromium } from "@playwright/test";
const S = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text().slice(0, 200)));
await p.goto("http://localhost:3000/signup");
await p.waitForLoadState("networkidle");
await p.getByRole("textbox", { name: /Your name/i }).fill("Dana Newco");
await p.getByRole("textbox", { name: /Email/i }).fill(`dana${Date.now()}@example.com`);
await p.getByRole("textbox", { name: /Password/i }).fill("Demo1234!xyz");
await p.getByRole("textbox", { name: /Company/i }).fill("Newco Rentals");
await p.getByRole("button", { name: /Create/i }).click();
await p.waitForURL("**/app/setup", { timeout: 120000 });
await p.waitForLoadState("networkidle");
await p.screenshot({ path: `${S}/onb1.png`, fullPage: true });
await p.getByRole("textbox", { name: "Office phone" }).fill("312-555-0100");
await p.getByRole("textbox", { name: "Street address" }).fill("1 Main St");
await p.getByRole("button", { name: "Save and continue" }).click();
await p.getByRole("heading", { name: "Add your properties" }).waitFor();
await p.screenshot({ path: `${S}/onb2.png`, fullPage: true });
await p.getByRole("button", { name: "Load sample data" }).click();
await p.waitForURL("**/app/overview?welcome=sample", { timeout: 180000 });
await p.waitForLoadState("networkidle");
await p.screenshot({ path: `${S}/onb3.png`, fullPage: true });
console.log("errors:", errs);
await b.close();
