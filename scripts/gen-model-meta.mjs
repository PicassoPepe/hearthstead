/**
 * Rewrite src/server/dal/model-meta.generated.ts from Prisma.dmmf.
 * Run on Node after `prisma generate` when the schema changes. Workers cannot read dmmf.
 */
import { writeFileSync } from "node:fs";
import { Prisma } from "@prisma/client";

const models = Prisma.dmmf.datamodel.models.map((m) => {
  const names = new Set(m.fields.map((f) => f.name));
  const orgField = m.name === "Organization" ? "id" : names.has("organizationId") ? "organizationId" : null;
  return { name: m.name, orgField, softDelete: names.has("deletedAt") };
});

const body = `/* Generated by scripts/gen-model-meta.mjs. Do not edit by hand. */
export type OrgField = "organizationId" | "id" | null;
export type ModelMeta = { orgField: OrgField; softDelete: boolean };

export const MODEL_META: Record<string, ModelMeta> = {
${models.map((m) => `  ${JSON.stringify(m.name)}: { orgField: ${m.orgField === null ? "null" : JSON.stringify(m.orgField)}, softDelete: ${m.softDelete} },`).join("\n")}
};
`;

writeFileSync(new URL("../src/server/dal/model-meta.generated.ts", import.meta.url), body);
console.log(`Wrote model metadata for ${models.length} models.`);
